"""
Дешёвый предфильтр сообщений группы перед отправкой в LLM.

Зачем: бот читает каждое сообщение классного чата, а там в основном
переписка. Без фильтра каждое «привет» и «спасибо» превращается в платный
вызов модели. Фильтр отсекает заведомо не-ДЗ по локальным признакам.

Принцип — асимметрия ошибок. Пропустить лишнее сообщение в LLM дёшево
(модель ответит null), потерять настоящее ДЗ дорого. Поэтому фильтр
намеренно нестрогий: сомнение трактуется в пользу отправки.
"""

from __future__ import annotations

import re

# Минимальная длина осмысленного ДЗ
MIN_LENGTH = 10

# Прямые указания на домашнее задание
_HOMEWORK_WORDS = {
    "дз", "домашка", "домашнее", "задание", "задали", "задано", "задать",
    "упражнение", "упр", "параграф", "стр", "страница", "номер",
    "выучить", "прочитать", "решить", "написать", "сделать", "повторить",
    "подготовить", "принести", "доделать", "переписать", "конспект",
    "сочинение", "изложение", "реферат", "доклад", "презентация",
    "задача", "задачи", "пример", "примеры", "таблица", "правило",
    "наизусть", "пересказ", "перевод", "словарь",
    # Английские маркеры из учебников
    "homework", "exercise", "unit", "workbook", "vocabulary", "page",
}

# Слова, характерные для англоязычных учебников в сокращениях
_SHORT_MARKERS = {"hw", "ex", "wb", "sb", "p", "pg"}

# Признаки сообщения о замене или отмене урока
_OVERRIDE_WORDS = {
    "вместо", "замена", "заменят", "заменили", "замену",
    "отменили", "отменяется", "отмена", "отменен", "отменён",
    "перенесли", "перенос", "переносится", "не будет",
}

# Явные признаки болтовни. Работают только если нет ни одного маркера ДЗ.
_CHITCHAT_PATTERNS = [
    r"^\s*(привет|здравствуйте|добрый день|доброе утро|добрый вечер|хай|ку)\b",
    r"^\s*(спасибо|благодарю|пожалуйста|не за что)\b",
    r"^\s*(да|нет|ок|окей|ага|угу|хорошо|понял|поняла|ясно|плюс)\s*[.!]*\s*$",
    r"^\s*(пока|до завтра|спокойной ночи|доброй ночи)\b",
    r"^\s*\+*\s*$",
    r"^\s*(ха+|хех|лол|ор|ржу)\b",
]

_CHITCHAT_RE = [re.compile(p, re.IGNORECASE) for p in _CHITCHAT_PATTERNS]

# Токенизация: слова из букв и цифр, без пунктуации
_TOKEN_RE = re.compile(r"[а-яёa-z0-9]+", re.IGNORECASE)

# Ссылка на пункт учебника: «стр.45», «§8», «упр 12», «p. 30», «№5»
_REFERENCE_RE = re.compile(
    r"(§\s*\d+|№\s*\d+|\bстр\w*\.?\s*\d+|\bупр\w*\.?\s*\d+"
    r"|\bp\.?\s*\d+|\bex\.?\s*\d+|\bunit\s*\d+)",
    re.IGNORECASE,
)


def _tokens(text: str) -> set[str]:
    return {t.lower() for t in _TOKEN_RE.findall(text)}


def has_homework_markers(text: str) -> bool:
    """Есть ли в тексте хоть один признак домашнего задания."""
    if _REFERENCE_RE.search(text):
        return True
    tokens = _tokens(text)
    return bool(tokens & _HOMEWORK_WORDS) or bool(tokens & _SHORT_MARKERS)


def has_override_markers(text: str) -> bool:
    """Похоже ли сообщение на замену или отмену урока."""
    lowered = text.lower()
    if "не будет" in lowered:
        return True
    return bool(_tokens(text) & _OVERRIDE_WORDS)


def is_probably_chitchat(text: str) -> bool:
    """Похоже ли сообщение на обычную переписку (при отсутствии маркеров ДЗ)."""
    return any(p.search(text) for p in _CHITCHAT_RE)


def should_analyze(text: str | None) -> bool:
    """
    Стоит ли отправлять текст в LLM.

    Отсекаются: пустые и слишком короткие сообщения, явная болтовня без
    признаков ДЗ, а также сообщения без единого маркера задания.
    Всё остальное уходит в модель.
    """
    if not text:
        return False

    stripped = text.strip()
    if len(stripped) < MIN_LENGTH:
        return False

    if has_homework_markers(stripped) or has_override_markers(stripped):
        return True

    # Маркеров нет — короткая болтовня отсекается наверняка
    if is_probably_chitchat(stripped):
        return False

    # Длинное сообщение без маркеров всё же может оказаться ДЗ,
    # сформулированным непривычно — отдаём модели.
    return len(stripped) >= 25


def normalize_task(subject: str, task: str) -> str:
    """
    Ключ кеша оценки времени: предмет и задание без регистра, пунктуации
    и лишних пробелов. «§8, задачи 1-3» и «§ 8 задачи 1 3» дают один ключ.
    """
    combined = f"{subject} {task}"
    return " ".join(sorted_tokens(combined))


def sorted_tokens(text: str) -> list[str]:
    """Токены в исходном порядке, приведённые к нижнему регистру."""
    return [t.lower() for t in _TOKEN_RE.findall(text)]
